-- =====================================================
-- CRM Application - Database Schema (PostgreSQL 14+)
-- Run while connected to crm_db as crm_user
--   pgAdmin: right-click crm_db > Query Tool, open this file, press F5
--   psql:    psql -U crm_user -d crm_db -f database/schema.sql
-- Re-running it wipes and recreates every table.
-- =====================================================

-- Drop in reverse order so the script can be re-run (CASCADE also drops the home page views)
DROP TABLE IF EXISTS email_attachments CASCADE;
DROP TABLE IF EXISTS emails CASCADE;
DROP TABLE IF EXISTS notifications CASCADE;
DROP TABLE IF EXISTS notes CASCADE;
DROP TABLE IF EXISTS stage_history CASCADE;
DROP TABLE IF EXISTS tasks CASCADE;
DROP TABLE IF EXISTS opportunities CASCADE;
DROP TABLE IF EXISTS leads CASCADE;
DROP TABLE IF EXISTS contacts CASCADE;
DROP TABLE IF EXISTS accounts CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- updated_at is set automatically on every UPDATE (MySQL did this with ON UPDATE CURRENT_TIMESTAMP)
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 1. USERS: salespeople, managers, admins
CREATE TABLE users (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR(100) NOT NULL,
  email         VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(20)  NOT NULL DEFAULT 'Salesperson'
                CHECK (role IN ('Salesperson','Manager','Admin')),
  is_active     BOOLEAN   NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. ACCOUNTS: customer companies
CREATE TABLE accounts (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(200) NOT NULL,
  industry   VARCHAR(100),
  phone      VARCHAR(30),
  website    VARCHAR(255),
  address    VARCHAR(500),
  owner_id   INT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_accounts_owner FOREIGN KEY (owner_id) REFERENCES users(id)
);
CREATE INDEX idx_accounts_name ON accounts (name);

-- 3. CONTACTS: people at an account (contact belongs to an account)
CREATE TABLE contacts (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  salutation VARCHAR(10) CHECK (salutation IN ('Mr.','Ms.','Mrs.','Dr.','Prof.')),
  first_name VARCHAR(50),
  last_name  VARCHAR(50) NOT NULL,
  -- full_name is filled automatically from first + last name (like Salesforce)
  full_name  VARCHAR(101) GENERATED ALWAYS AS (TRIM(COALESCE(first_name || ' ', '') || last_name)) STORED,
  job_title  VARCHAR(100),
  email      VARCHAR(255),
  phone      VARCHAR(30),
  account_id INT NOT NULL,
  owner_id   INT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_contacts_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT fk_contacts_owner   FOREIGN KEY (owner_id)   REFERENCES users(id)
);

-- 4. LEADS: enquiries. New -> Nurturing -> Demo -> Converted (to Opportunity) or Lost
--    Fields follow the Salesforce lead form: Salutation, First Name, Last Name (required), Company, Title, Industry
CREATE TABLE leads (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  salutation   VARCHAR(10) CHECK (salutation IN ('Mr.','Ms.','Mrs.','Dr.','Prof.')),
  first_name   VARCHAR(50),
  last_name    VARCHAR(50) NOT NULL,
  -- name is filled automatically from first + last name, so views and lists keep using "name"
  name         VARCHAR(101) GENERATED ALWAYS AS (TRIM(COALESCE(first_name || ' ', '') || last_name)) STORED,
  company      VARCHAR(200),
  title        VARCHAR(100),
  industry     VARCHAR(100),
  email        VARCHAR(255),
  phone        VARCHAR(30),
  source       VARCHAR(20) NOT NULL DEFAULT 'Other'
               CHECK (source IN ('Website','Referral','Phone','Email','Event','Social Media','Other')),
  stage        VARCHAR(20) NOT NULL DEFAULT 'New'
               CHECK (stage IN ('New','Nurturing','Demo','Converted','Lost')),
  demo_date    TIMESTAMP,
  lost_reason  VARCHAR(20)
               CHECK (lost_reason IN ('Price','Competitor','No response','No budget','Not interested','Other')),
  lost_notes   TEXT,
  converted_at TIMESTAMP,
  closed_at    TIMESTAMP,
  owner_id     INT NOT NULL,
  created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_leads_owner FOREIGN KEY (owner_id) REFERENCES users(id),
  -- Rule: a Lost lead must have a lost reason
  CONSTRAINT ck_leads_lost_reason CHECK (stage <> 'Lost' OR lost_reason IS NOT NULL)
);
CREATE INDEX idx_leads_stage   ON leads (stage);
CREATE INDEX idx_leads_name    ON leads (name);
CREATE INDEX idx_leads_company ON leads (company);
CREATE INDEX idx_leads_email   ON leads (email);

-- 5. OPPORTUNITIES: serious deals (opportunity belongs to an account)
--    Opportunity -> Proposal -> Won / Lost
CREATE TABLE opportunities (
  id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                VARCHAR(200) NOT NULL,
  stage               VARCHAR(20) NOT NULL DEFAULT 'Opportunity'
                      CHECK (stage IN ('Opportunity','Proposal','Won','Lost')),
  expected_value      NUMERIC(14,2),
  final_value         NUMERIC(14,2),
  expected_close_date DATE,
  -- % chance to win: Opportunity 20, Proposal 75, Won 100, Lost 0
  probability         SMALLINT NOT NULL DEFAULT 20 CHECK (probability BETWEEN 0 AND 100),
  lost_reason         VARCHAR(20)
                      CHECK (lost_reason IN ('Price','Competitor','No response','No budget','Not interested','Other')),
  lost_notes          TEXT,
  closed_at           TIMESTAMP,
  account_id          INT NOT NULL,
  primary_contact_id  INT,
  lead_id             INT UNIQUE,          -- the lead it was converted from
  owner_id            INT NOT NULL,
  created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_opps_account FOREIGN KEY (account_id)         REFERENCES accounts(id),
  CONSTRAINT fk_opps_contact FOREIGN KEY (primary_contact_id) REFERENCES contacts(id) ON DELETE SET NULL,
  CONSTRAINT fk_opps_lead    FOREIGN KEY (lead_id)            REFERENCES leads(id)    ON DELETE SET NULL,
  CONSTRAINT fk_opps_owner   FOREIGN KEY (owner_id)           REFERENCES users(id),
  -- Rules: Lost needs a reason, Won needs a final value
  CONSTRAINT ck_opps_lost_reason CHECK (stage <> 'Lost' OR lost_reason IS NOT NULL),
  CONSTRAINT ck_opps_won_value   CHECK (stage <> 'Won'  OR final_value IS NOT NULL)
);
CREATE INDEX idx_opps_stage ON opportunities (stage);
CREATE INDEX idx_opps_name  ON opportunities (name);

-- 6. TASKS: follow-ups. Linked to a lead OR an opportunity, or to neither (general task from "Add task")
CREATE TABLE tasks (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title          VARCHAR(200) NOT NULL,
  description    TEXT,
  due_date       TIMESTAMP NOT NULL,
  reminder_at    TIMESTAMP,
  reminder_sent  BOOLEAN NOT NULL DEFAULT FALSE,
  status         VARCHAR(20) NOT NULL DEFAULT 'Open'   CHECK (status IN ('Open','Done','Auto-closed')),
  priority       VARCHAR(10) NOT NULL DEFAULT 'Normal' CHECK (priority IN ('Low','Normal','High')),
  is_auto        BOOLEAN NOT NULL DEFAULT FALSE,   -- created by the system
  completed_at   TIMESTAMP,
  owner_id       INT NOT NULL,
  lead_id        INT,
  opportunity_id INT,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_tasks_owner FOREIGN KEY (owner_id)       REFERENCES users(id),
  CONSTRAINT fk_tasks_lead  FOREIGN KEY (lead_id)        REFERENCES leads(id),
  CONSTRAINT fk_tasks_opp   FOREIGN KEY (opportunity_id) REFERENCES opportunities(id),
  CONSTRAINT ck_tasks_parent CHECK (lead_id IS NULL OR opportunity_id IS NULL)   -- never both
);
CREATE INDEX idx_tasks_due       ON tasks (due_date);
CREATE INDEX idx_tasks_status    ON tasks (status);
CREATE INDEX idx_tasks_owner_due ON tasks (owner_id, status, due_date);   -- "Today's tasks" for one user

-- 7. STAGE_HISTORY: every stage change, who and when
CREATE TABLE stage_history (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_stage     VARCHAR(30),                -- NULL when the record is created
  to_stage       VARCHAR(30) NOT NULL,
  note           TEXT,
  changed_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  changed_by_id  INT NOT NULL,
  lead_id        INT,
  opportunity_id INT,
  CONSTRAINT fk_history_user FOREIGN KEY (changed_by_id)  REFERENCES users(id),
  CONSTRAINT fk_history_lead FOREIGN KEY (lead_id)        REFERENCES leads(id),
  CONSTRAINT fk_history_opp  FOREIGN KEY (opportunity_id) REFERENCES opportunities(id),
  CONSTRAINT ck_history_parent CHECK ((lead_id IS NULL) <> (opportunity_id IS NULL))
);
CREATE INDEX idx_history_changed_at ON stage_history (changed_at);

-- 8. NOTES: call/demo notes on a lead OR an opportunity
CREATE TABLE notes (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  body           TEXT NOT NULL,
  created_by_id  INT NOT NULL,
  lead_id        INT,
  opportunity_id INT,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notes_user FOREIGN KEY (created_by_id)  REFERENCES users(id),
  CONSTRAINT fk_notes_lead FOREIGN KEY (lead_id)        REFERENCES leads(id),
  CONSTRAINT fk_notes_opp  FOREIGN KEY (opportunity_id) REFERENCES opportunities(id),
  CONSTRAINT ck_notes_parent CHECK ((lead_id IS NULL) <> (opportunity_id IS NULL))
);

-- 9. NOTIFICATIONS: the bell icon (task reminders, overdue alerts)
CREATE TABLE notifications (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INT NOT NULL,
  task_id    INT,
  title      VARCHAR(200) NOT NULL,
  message    VARCHAR(500),
  link       VARCHAR(200),                -- page in the app to open, e.g. /leads/5
  is_read    BOOLEAN   NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notif_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_notif_task FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE SET NULL
);
CREATE INDEX idx_notif_user_unread ON notifications (user_id, is_read);

-- 10. EMAILS: emails sent from a lead / opportunity / contact / account page
CREATE TABLE emails (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject        VARCHAR(255) NOT NULL,
  body           TEXT NOT NULL,
  to_address     VARCHAR(500) NOT NULL,
  cc_address     VARCHAR(500),
  status         VARCHAR(10) NOT NULL DEFAULT 'Sent' CHECK (status IN ('Sent','Failed')),
  error          TEXT,                       -- why sending failed
  sent_by_id     INT NOT NULL,
  lead_id        INT,
  opportunity_id INT,
  contact_id     INT,
  account_id     INT,
  sent_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_emails_user    FOREIGN KEY (sent_by_id)     REFERENCES users(id),
  CONSTRAINT fk_emails_lead    FOREIGN KEY (lead_id)        REFERENCES leads(id),
  CONSTRAINT fk_emails_opp     FOREIGN KEY (opportunity_id) REFERENCES opportunities(id),
  CONSTRAINT fk_emails_contact FOREIGN KEY (contact_id)     REFERENCES contacts(id),
  CONSTRAINT fk_emails_account FOREIGN KEY (account_id)     REFERENCES accounts(id),
  CONSTRAINT ck_emails_parent  CHECK (COALESCE(lead_id, opportunity_id, contact_id, account_id) IS NOT NULL)
);
CREATE INDEX idx_emails_lead ON emails (lead_id);
CREATE INDEX idx_emails_opp  ON emails (opportunity_id);

-- 11. EMAIL_ATTACHMENTS: files sent with an email (stored in the database)
CREATE TABLE email_attachments (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_id     INT NOT NULL,
  filename     VARCHAR(255) NOT NULL,
  content_type VARCHAR(100) NOT NULL,
  size_bytes   INT NOT NULL,
  data         BYTEA NOT NULL,
  CONSTRAINT fk_attach_email FOREIGN KEY (email_id) REFERENCES emails(id) ON DELETE CASCADE
);

-- updated_at triggers for the tables that have that column
CREATE TRIGGER trg_users_updated_at         BEFORE UPDATE ON users         FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_accounts_updated_at      BEFORE UPDATE ON accounts      FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_contacts_updated_at      BEFORE UPDATE ON contacts      FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_leads_updated_at         BEFORE UPDATE ON leads         FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_opportunities_updated_at BEFORE UPDATE ON opportunities FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_tasks_updated_at         BEFORE UPDATE ON tasks         FOR EACH ROW EXECUTE FUNCTION set_updated_at();
